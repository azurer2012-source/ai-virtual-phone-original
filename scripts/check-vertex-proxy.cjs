const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const ts = require(root + '/node_modules/typescript');
const Module = require('module');
function compile(file, override = {}) {
  const filename = path.join(root, file);
  const mod = new Module(filename);
  mod.filename = filename;
  mod.paths = Module._nodeModulePaths(path.dirname(filename));
  const original = mod.require.bind(mod);
  mod.require = id => override[id] || original(id);
  mod._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, filename);
  return mod.exports;
}
const client = compile('lib/server/vertex-client.ts');
process.env.VERTEX_PROXY_TOKEN = 'a'.repeat(64);
process.env.GOOGLE_CLOUD_PROJECT = 'test-project';
process.env.VERTEX_MODEL = 'google/gemini-test';
const headers = { authorization: 'Bearer ' + process.env.VERTEX_PROXY_TOKEN, 'content-type': 'application/json' };
const request = (body, custom = headers) => new Request('https://example.test/api/vertex/v1/chat/completions', { method: 'POST', headers: custom, body: JSON.stringify(body) });
const body = { model: process.env.VERTEX_MODEL, messages: [{role:'user',content:'hello'}] };
const route = compile('app/api/vertex/v1/chat/completions/route.ts', { '@/lib/server/vertex-client': {...client, vertexAccessToken: async () => 'mock-google-token'} });
const models = compile('app/api/vertex/v1/models/route.ts', { '@/lib/server/vertex-client': client });
(async () => {
  assert.equal((await route.POST(request(body, {}))).status, 401);
  assert.equal((await route.POST(request(body, {...headers, origin:'https://evil.test'}))).status, 403);
  assert.equal((await route.POST(request({...body,model:'google/other'}))).status,400);
  assert.equal((await route.POST(request({...body,tools:[]}))).status,400);
  assert.equal((await route.POST(request({...body,max_tokens:999999}))).status,400);
  assert.equal((await route.POST(request({...body,messages:[{role:'user',content:'x'.repeat(1024*1024)}]}))).status,413);
  const malformed = new Request('https://example.test', {method:'POST',headers,body:'{'});
  assert.equal((await route.POST(malformed)).status,400);
  assert.equal((await models.GET(new Request('https://example.test',{headers}))).status,200);
  let calls = 0;
  global.fetch = async (url, options) => {
    calls++;
    assert.equal(new URL(url).hostname, 'aiplatform.googleapis.com');
    assert.equal(options.headers.Authorization,'Bearer mock-google-token');
    const payload = JSON.parse(options.body);
    assert.equal(payload.repetition_penalty,undefined);
    return new Response(payload.stream ? 'data: {"choices":[]}\n\ndata: [DONE]\n\n' : '{"choices":[]}');
  };
  const normal = await route.POST(request({...body,repetition_penalty:1}));
  assert.equal(normal.status,200); assert.deepEqual(await normal.json(),{choices:[]});
  const streaming = await route.POST(request({...body,stream:true}));
  assert.match(streaming.headers.get('content-type'),/text\/event-stream/);
  assert.match(await streaming.text(),/\[DONE\]/);
  let cancelled = false;
  global.fetch = async (_, options) => { options.signal.addEventListener('abort',()=>{cancelled=true}); return new Response(new ReadableStream()); };
  const pending = await route.POST(request({...body,stream:true}));
  await pending.body.cancel(); assert.equal(cancelled,true);
  global.fetch = async () => new Response('private upstream detail',{status:403});
  const denied = await route.POST(request(body));
  assert.equal(denied.status,502); assert.doesNotMatch(await denied.text(),/private upstream detail/);
  assert.equal(calls,2);
  console.log('PASS: auth, origin, model, tools, tokens, body size, malformed JSON, models, JSON, SSE, cancellation, error redaction');
})().catch(e=>{console.error(e);process.exitCode=1});
